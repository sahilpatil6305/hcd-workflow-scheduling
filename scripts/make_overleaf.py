"""Convert manuscript/main.tex (article layout) into an Overleaf-ready IEEEtran project in overleaf/ and zip it.
Usage: python scripts/make_overleaf.py"""
import os, shutil, glob, zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OL = os.path.join(ROOT, "overleaf")
HEADER = r'''% =====================================================================
% Overleaf project: Overleaf > New Project > Upload Project (this zip).
% Compiler: pdfLaTeX (default). Bibliography: BibTeX (automatic on Overleaf).
% Files: main.tex, references.bib, tables/*.tex, figures/*.pdf
% =====================================================================
\documentclass[conference]{IEEEtran}
\IEEEoverridecommandlockouts
\usepackage{cite}
\usepackage{amsmath,amssymb,amsfonts}
\usepackage{booktabs}
\usepackage{graphicx}
\usepackage{algorithm}
\usepackage{algpseudocode}
\usepackage{textcomp}
\usepackage{xcolor}
\usepackage[hidelinks]{hyperref}
\graphicspath{{figures/}}
\newcommand{\EFT}{\textsf{EFT}}
\newcommand{\ECT}{\textsf{ECT}}
\newcommand{\RT}{\textsf{RT}}

\begin{document}

\title{__TITLE__}

% ---- TODO: add co-authors (copy the commented block) ----
\author{\IEEEauthorblockN{Sahil Patil}
\IEEEauthorblockA{\textit{Department of Computer Science and Engineering}\\
\textit{Indian Institute of Technology (BHU) Varanasi}\\
Varanasi, India\\
patilsahil.sainath.cse22@itbhu.ac.in}
% \and
% \IEEEauthorblockN{Second Author}
% \IEEEauthorblockA{\textit{Department} \\ \textit{Institution}\\ City, Country \\ email}
}

\maketitle
'''


def main():
    src = open(os.path.join(ROOT, "manuscript", "main.tex")).read()
    t0 = src.index(r"\title{") + len(r"\title{")
    depth, i = 1, t0
    while depth:
        depth += {"{": 1, "}": -1}.get(src[i], 0); i += 1
    title = src[t0:i - 1].replace(r"\Large\bfseries ", "")
    body = src[src.index(r"\maketitle") + len(r"\maketitle"):]
    body = body.replace(r"\end{abstract}", "\\end{abstract}\n\n\\begin{IEEEkeywords}\nworkflow scheduling, fault tolerance, "
                        "failure-aware placement, online estimation, change detection, WfCommons\n\\end{IEEEkeywords}", 1)
    body = body.replace("../figures/", "figures/")
    a, b = body.index(r"\begin{thebibliography}"), body.index(r"\end{thebibliography}") + len(r"\end{thebibliography}")
    body = body[:a] + "\\bibliographystyle{IEEEtran}\n\\bibliography{references}" + body[b:]
    body = body.replace("\\appendix\n", "\\appendices\n").replace(r"\section*{Reproducibility}", r"\section*{Data and Code Availability}")
    shutil.rmtree(OL, ignore_errors=True)
    os.makedirs(os.path.join(OL, "figures")); os.makedirs(os.path.join(OL, "tables"))
    open(os.path.join(OL, "main.tex"), "w").write(HEADER.replace("__TITLE__", title) + body)
    for f in glob.glob(os.path.join(ROOT, "manuscript", "tables", "*.tex")):
        shutil.copy(f, os.path.join(OL, "tables"))
    used = [l.split("figures/")[1].split("}")[0] for l in body.splitlines() if "includegraphics" in l]
    for f in used:
        shutil.copy(os.path.join(ROOT, "figures", f), os.path.join(OL, "figures", f))
    shutil.copy(os.path.join(ROOT, "manuscript", "references.bib"), OL)
    open(os.path.join(OL, "README_OVERLEAF.txt"), "w").write(
        "1. overleaf.com > New Project > Upload Project > choose overleaf_paper.zip\n"
        "2. Compiler: pdfLaTeX (default). Click Recompile.\n"
        "3. Edit the \\author block in main.tex; add authors for jnca2025robust in references.bib.\n"
        "Tables are generated by scripts/make_tables.py and scripts/make_tables_v51.py; regenerate rather than hand-edit.\n")
    zp = os.path.join(os.path.dirname(ROOT), "overleaf_paper.zip")
    with zipfile.ZipFile(zp, "w", zipfile.ZIP_DEFLATED) as z:
        for dp, _, fs in os.walk(OL):
            for f in fs:
                z.write(os.path.join(dp, f), os.path.relpath(os.path.join(dp, f), OL))
    print("wrote", OL, "and", zp, "figures:", used)


if __name__ == "__main__":
    main()
